"""Figures for the rebuttal status report (reviews/aistats/report/).

Usage:  python -m rebuttal.report_figures OUT_DIR

Numbers marked "from wave1_summaries.md" are copied from rebuttal/out/wave1_summaries.md
(generated by rebuttal/wave1_summaries.py from results_v3/summary). The decision-task
numbers come from the reproducible rerun in results_v3_rebuttal/main_v3, and the bound
figure reads rebuttal/out/bound_main_v3.csv.
"""

import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

# One color per entity, in the fixed categorical order of the reference palette.
BLUE, ORANGE, AQUA, YELLOW, MAGENTA = "#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"
COLOR = {"CSCD": BLUE, "Bootstrap": ORANGE, "Pool": AQUA, "Single run": YELLOW, "Uncalibrated": MAGENTA}
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
METHODS = ["PC", "GES", "FCI"]

plt.rcParams.update({
    "font.family": "DejaVu Sans", "font.size": 9, "axes.edgecolor": INK2, "axes.labelcolor": INK2,
    "xtick.color": INK2, "ytick.color": INK2, "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.axisbelow": True,
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "legend.frameon": False, "axes.titlesize": 10, "axes.titleweight": "bold",
})


def save(fig, out_dir, name):
    fig.savefig(os.path.join(out_dir, name), dpi=200, bbox_inches="tight")
    plt.close(fig)


def bars(ax, groups, series, values, colors, width=0.38, labels=True, fmt="{:.2f}"):
    """Grouped bars with a small gap between neighbours and value labels on top."""
    x = np.arange(len(groups))
    n = len(series)
    gap = 0.015 * max(max(v) for v in values)  # label offset, relative to the tallest bar
    for i, (name, color) in enumerate(zip(series, colors)):
        pos = x + (i - (n - 1) / 2) * width
        vals = values[i]
        ax.bar(pos, vals, width * 0.92, color=color, label=name, zorder=2)
        if labels:
            for p, v in zip(pos, vals):
                ax.text(p, v + gap, fmt.format(v), ha="center", va="bottom", fontsize=7, color=INK2)
    ax.set_xticks(x, groups)
    ax.grid(axis="x", visible=False)


def fig_flags(out_dir):
    """Native flag rate of G-hat, hidden hubs vs. control (from wave1_summaries.md, section D)."""
    rules = ["CSCD", "Uncalibrated\nreference", "Bootstrap\n(own quantile)"]
    scenario = {"PC": [0.90, 0.47, 0.00], "GES": [0.87, 0.97, 0.00], "FCI": [0.33, 0.30, 0.00]}
    control = {"PC": [0.07, 0.00, 0.00], "GES": [0.17, 0.37, 0.00], "FCI": [0.00, 0.40, 0.00]}
    fig, axes = plt.subplots(1, 3, figsize=(10, 3.2), sharey=True)
    for ax, m in zip(axes, METHODS):
        bars(ax, rules, ["Hidden confounders (should flag)", "No confounders (should not flag)"],
             [scenario[m], control[m]], [BLUE, ORANGE])
        ax.set_title(m)
        ax.set_ylim(0, 1.12)
        ax.tick_params(axis="x", labelsize=7.5)
    axes[0].set_ylabel("Fraction of runs flagged")
    axes[0].legend(loc="upper center", bbox_to_anchor=(1.6, -0.25), ncol=2)
    save(fig, out_dir, "fig1_flag_rates.png")


def fig_gating(out_dir):
    """Skeleton error of G-hat over all 360 pooled runs vs. runs CSCD does not flag (section E)."""
    all_runs = [0.068, 0.067, 0.069]
    kept = [0.034, 0.028, 0.048]
    fig, ax = plt.subplots(figsize=(5, 3))
    bars(ax, METHODS, ["All runs", "Runs not flagged by CSCD"], [all_runs, kept], [INK2, BLUE], fmt="{:.3f}")
    ax.set_ylabel("Skeleton error rate of $\\hat G$")
    ax.set_ylim(0, 0.085)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=2)
    save(fig, out_dir, "fig2_gating.png")


def fig_fdp(out_dir):
    """Mean per-run FDP of accepted adjacency claims with 95% cluster CIs (section C)."""
    data = {  # estimator: {method: (mean, lo, hi)}
        "CSCD": {"PC": (0.021, 0.009, 0.034), "GES": (0.089, 0.064, 0.117), "FCI": (0.008, 0.000, 0.018)},
        "Pool": {"PC": (0.015, 0.005, 0.028), "GES": (0.031, 0.007, 0.060), "FCI": (0.004, 0.000, 0.010)},
        "Bootstrap": {"PC": (0.005, 0.000, 0.014), "GES": (0.027, 0.006, 0.055), "FCI": (0.002, 0.000, 0.006)},
        "Single run": {"PC": (0.055, 0.031, 0.083), "GES": (0.094, 0.058, 0.137), "FCI": (0.050, 0.028, 0.078)},
    }
    names = list(data)
    fig, axes = plt.subplots(1, 3, figsize=(10, 2.6), sharex=True)
    for ax, m in zip(axes, METHODS):
        for i, est in enumerate(names):
            mean, lo, hi = data[est][m]
            y = len(names) - 1 - i
            ax.plot([lo, hi], [y, y], color=COLOR[est], lw=2, solid_capstyle="round", zorder=2)
            ax.plot(mean, y, "o", ms=8, color=COLOR[est], mec=SURFACE, mew=1, zorder=3)
        ax.set_yticks(range(len(names)), names[::-1] if ax is axes[0] else [""] * len(names))
        ax.set_title(m)
        ax.grid(axis="y", visible=False)
        ax.set_xlim(-0.005, 0.15)
    axes[1].set_xlabel("Mean per-run false discovery proportion of accepted adjacencies (95% CI)")
    save(fig, out_dir, "fig3_fdp.png")


def fig_exceedance(out_dir):
    """Fresh-chunk exceedance: pooled Clopper-Pearson vs. cluster bootstrap over runs, N = 9 (section A)."""
    rows = {  # alpha: {method: (rate, pooled lo, pooled hi, cluster lo, cluster hi)}
        0.1: {"PC": (0.090, 0.087, 0.095, 0.083, 0.099), "GES": (0.097, 0.092, 0.101, 0.088, 0.105),
              "FCI": (0.099, 0.095, 0.103, 0.091, 0.108)},
        0.2: {"PC": (0.188, 0.182, 0.193, 0.177, 0.199), "GES": (0.191, 0.186, 0.197, 0.180, 0.203),
              "FCI": (0.198, 0.193, 0.204, 0.187, 0.210)},
    }
    fig, axes = plt.subplots(1, 2, figsize=(9, 2.4))
    for ax, alpha in zip(axes, rows):
        for i, m in enumerate(METHODS):
            rate, plo, phi, clo, chi = rows[alpha][m]
            y = 2 - i
            ax.plot([clo, chi], [y - 0.12, y - 0.12], color=BLUE, lw=2, solid_capstyle="round",
                    label="Cluster bootstrap over runs (new)" if i == 0 else None)
            ax.plot([plo, phi], [y + 0.12, y + 0.12], color=INK2, lw=2, solid_capstyle="round",
                    label="Pooled Clopper–Pearson (paper)" if i == 0 else None)
            ax.plot(rate, y, "o", ms=7, color=INK, mec=SURFACE, mew=1.5)
        ax.axvline(alpha, color=ORANGE, lw=1.5, ls="--", label="Nominal $\\alpha$")
        ax.set_yticks(range(3), METHODS[::-1])
        ax.grid(axis="y", visible=False)
        ax.set_title(f"$\\alpha = {alpha}$, N = 9, 500 runs")
        ax.set_xlabel("Exceedance on fresh chunks")
    axes[0].legend(loc="upper center", bbox_to_anchor=(1.1, -0.35), ncol=3)
    save(fig, out_dir, "fig4_exceedance.png")


def fig_decision(out_dir):
    """Corrected Table 27 (reproducible rerun): coverage, and paired bias differences."""
    coverage = {"CSCD": [0.61, 0.58, 0.72], "Pool": [0.74, 0.73, 0.74],
                "Bootstrap": [0.66, 0.62, 0.77], "Single run": [0.21, 0.26, 0.54]}
    fig, ax = plt.subplots(figsize=(7, 3))
    bars(ax, METHODS, list(coverage), list(coverage.values()), [COLOR[k] for k in coverage], width=0.2)
    ax.set_ylabel("Range coverage of the true effect")
    ax.set_ylim(0, 0.9)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=4)
    save(fig, out_dir, "fig5_decision_coverage.png")

    diffs = {  # comparison: {method: (mean, lo, hi)} of bias(CSCD) - bias(comparison)
        "Single run": {"PC": (-0.038, -0.080, -0.006), "GES": (-0.010, -0.037, 0.012), "FCI": (-0.013, -0.031, 0.005)},
        "Pool": {"PC": (0.002, -0.026, 0.020), "GES": (-0.036, -0.068, -0.006), "FCI": (-0.001, -0.005, 0.002)},
        "Bootstrap": {"PC": (0.021, -0.012, 0.053), "GES": (-0.054, -0.104, -0.001), "FCI": (-0.008, -0.025, 0.010)},
    }
    fig, axes = plt.subplots(1, 3, figsize=(10, 2.3), sharex=True)
    for ax, m in zip(axes, METHODS):
        for i, comp in enumerate(diffs):
            mean, lo, hi = diffs[comp][m]
            y = 2 - i
            ax.plot([lo, hi], [y, y], color=COLOR[comp], lw=2, solid_capstyle="round")
            ax.plot(mean, y, "o", ms=8, color=COLOR[comp], mec=SURFACE, mew=1)
        ax.axvline(0, color=INK2, lw=1)
        ax.set_yticks(range(3), [f"vs {c}" for c in list(diffs)[::-1]] if ax is axes[0] else [""] * 3)
        ax.grid(axis="y", visible=False)
        ax.set_title(m)
    axes[1].set_xlabel("Bias of CSCD minus bias of the comparison (95% CI; below 0 favours CSCD)")
    save(fig, out_dir, "fig6_decision_bias.png")


def fig_bound(out_dir, bound_csv):
    """Per run: false adjacencies the bound allows vs. the worst admitted graph's actual count."""
    d = pd.read_csv(bound_csv)
    rng = np.random.default_rng(0)
    fig, ax = plt.subplots(figsize=(6, 3))
    for i, m in enumerate(METHODS):
        g = d[d.method == m.lower()]
        for offset, col, name, color in ((-0.15, "bound_tight", "Allowed by the bound", BLUE),
                                         (0.15, "observed_max_false", "Observed (worst admitted graph)", ORANGE)):
            x = i + offset + rng.uniform(-0.06, 0.06, len(g))
            ax.plot(x, g[col], "o", ms=4, color=color, alpha=0.75, label=name if i == 0 else None)
            ax.plot([i + offset - 0.1, i + offset + 0.1], [g[col].median()] * 2, color=INK, lw=2)
    ax.set_xticks(range(3), METHODS)
    ax.grid(axis="x", visible=False)
    ax.set_ylabel("False adjacencies per run")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=2)
    save(fig, out_dir, "fig7_bound.png")


def main(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    fig_flags(out_dir)
    fig_gating(out_dir)
    fig_fdp(out_dir)
    fig_exceedance(out_dir)
    fig_decision(out_dir)
    fig_bound(out_dir, "rebuttal/out/bound_main_v3.csv")


if __name__ == "__main__":
    main(sys.argv[1])
